// The marker is saved with the dataset: reloads never duplicate or resurrect
// deleted fixtures. Existing records always win ID collisions.
export function initializeDemoData(existing, now = new Date()) {
  if (existing.__demo?.some((entry) => entry.id === demoVersion))
    return existing
  const result = { ...existing }
  for (const [collection, entries] of Object.entries(createDemoData(now))) {
    const current = existing[collection] || []
    const ids = new Set(current.map((entry) => entry.id))
    result[collection] = [
      ...current,
      ...entries.filter((entry) => !ids.has(entry.id)),
    ]
  }
  result.__demo = [
    ...(existing.__demo || []),
    {
      id: demoVersion,
      name: "Base fictícia de testes",
      created: now.toISOString(),
    },
  ]
  return result
}
